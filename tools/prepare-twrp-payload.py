"""Derive private build inputs from user-supplied Android boot images."""
import argparse
import gzip
import hashlib
import lzma
from pathlib import Path
import struct


def digest(data):
    return hashlib.sha256(data).hexdigest()


def image(data, version):
    if len(data) < 48 or data[:8] != b'ANDROID!':
        raise ValueError('invalid Android header')
    page, ver = struct.unpack_from('<II', data, 36)
    minimum = 1660 if version == 2 else 1632
    if ver != version or page < minimum or page & (page - 1) or page > len(data):
        raise ValueError('invalid version or page size')
    return page


def prepare(stock, twrp, out, expect_stock, expect_twrp):
    out = Path(out)
    if out.exists():
        raise ValueError('output directory already exists')
    b, t = Path(stock).read_bytes(), Path(twrp).read_bytes()
    if digest(b) != expect_stock or digest(t) != expect_twrp:
        raise ValueError('input SHA-256 mismatch')
    page = image(b, 2)
    size = struct.unpack_from('<I', b, 8)[0]
    if not size or page + size > len(b):
        raise ValueError('truncated kernel')
    k = gzip.decompress(b[page:page + size])
    if len(k) < 64 or k[56:60] != b'ARM\x64':
        raise ValueError('not an ARM64 kernel')
    offset, image_size, flags = struct.unpack_from('<QQQ', k, 8)
    if not flags & 8 or offset >= 2**21 or not len(k) <= image_size <= 128 * 2**20 - offset:
        raise ValueError('unsupported ARM64 placement')
    tp = image(t, 0)
    if struct.unpack_from('<I', t, 8)[0] != 0:
        raise ValueError('TWRP must be ramdisk-only')
    ts = struct.unpack_from('<I', t, 16)[0]
    if ts < 32 or ts > 64 * 2**20 or tp + ts > len(t):
        raise ValueError('invalid TWRP ramdisk size')
    rd = t[tp:tp + ts]
    if rd[:2] != b'\x1f\x8b':
        raise ValueError('TWRP ramdisk must be gzip')
    z = lzma.compress(k, format=lzma.FORMAT_ALONE, preset=6)
    z = z[:5] + struct.pack('<Q', len(k)) + z[13:]
    if lzma.decompress(z, format=lzma.FORMAT_ALONE) != k:
        raise ValueError('LZMA roundtrip failed')
    header = '/* Generated private input identities. Do not commit. */\n'
    for name, value in [('KERNEL_RAW_SIZE', len(k)), ('KERNEL_LZMA_SIZE', len(z)),
                        ('KERNEL_IMAGE_SIZE', image_size), ('KERNEL_OFFSET', offset), ('TWRP_SIZE', len(rd))]:
        header += f'#define DBY_{name} {value}UL\n'
    for name, value in [('kernel_raw_sha', hashlib.sha256(k).digest()),
                        ('kernel_lzma_sha', hashlib.sha256(z).digest()),
                        ('twrp_sha', hashlib.sha256(rd).digest()), ('twrp_prefix', rd[:32])]:
        header += f'static const unsigned char dby_{name}[] = {{' + ','.join(map(str, value)) + '};\n'
    # The assembler macro expands to an absolute path supplied by build.sh.
    # Keeping the path out of this file makes all generated bytes deterministic.
    asm = '.section .rodata.dby_stock,"a"\n.balign 16\n.global dby_stock_lzma\n.global dby_stock_lzma_end\ndby_stock_lzma:\n.incbin DBY_STOCK_PAYLOAD\ndby_stock_lzma_end:\n.section .note.GNU-stack,"",%progbits\n'
    out.mkdir(parents=True)
    (out / 'stock-kernel.lzma').write_bytes(z)
    (out / 'dby-twrp-data.h').write_text(header)
    (out / 'dby-stock.S').write_text(asm)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ('stock-recovery', 'twrp', 'out-dir', 'expect-stock-sha256', 'expect-twrp-sha256'):
        p.add_argument('--' + name, required=True)
    a = p.parse_args()
    try:
        prepare(a.stock_recovery, a.twrp, a.out_dir, a.expect_stock_sha256, a.expect_twrp_sha256)
    except (ValueError, OSError, EOFError, lzma.LZMAError) as e:
        p.exit(1, f'payload: {e}\n')


if __name__ == '__main__':
    main()
